uint16_t get_tapping_term(uint16_t keycode, keyrecord_t *record) {
    if (IS_QK_MOD_TAP(keycode) && (QK_MOD_TAP_GET_MODS(keycode) & MOD_MASK_SHIFT)) {
        return TAPPING_TERM - 150;  // resolve shift quickly
    }
    return TAPPING_TERM;
}

